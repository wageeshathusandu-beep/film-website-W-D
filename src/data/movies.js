export const getMovieById = (id) => {
  return movies.find((m) => m.id === parseInt(id))
}

export const getMoviesByCategory = (category) => {
  return movies.filter((m) => m.category === category)
}

export const getFeaturedMovies = () => {
  return movies.filter((m) => m.isFeatured)
}

export const getRelatedMovies = (currentId, category) => {
  return movies.filter((m) => m.id !== parseInt(currentId) && m.category === category).slice(0, 4)
}
